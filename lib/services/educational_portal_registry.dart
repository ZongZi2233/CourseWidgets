  /// 综合检索入口（支持全拼、简拼、中文包含、系统类型搜索，以及全网智能直达入口）
  static List<EducationalPortal> search(String query) {
    final clean = query.trim().toLowerCase();
    if (clean.isEmpty) {
      return [...genericSystems, ...universityPortals];
    }

    final results = <EducationalPortal>[];

    for (final portal in genericSystems) {
      if (portal.name.toLowerCase().contains(clean) ||
          portal.pinyin.toLowerCase().contains(clean) ||
          portal.systemType.toLowerCase().contains(clean)) {
        results.add(portal);
      }
    }

    for (final portal in universityPortals) {
      if (portal.name.toLowerCase().contains(clean) ||
          portal.pinyin.toLowerCase().contains(clean) ||
          portal.systemType.toLowerCase().contains(clean) ||
          (portal.defaultUrl != null && portal.defaultUrl!.toLowerCase().contains(clean))) {
        results.add(portal);
      }
    }

    // 智能直达通道：任何大学或学院（哪怕未在预设名录中），均可一键在内置浏览器中检索并访问
    final directSearchName = query.trim();
    final directPortal = EducationalPortal(
      name: '$directSearchName 教务系统直达',
      pinyin: clean,
      systemType: '网络智能直达',
      defaultUrl: 'https://www.baidu.com/s?wd=${Uri.encodeComponent('$directSearchName 教务系统')}',
      hint: '一键在内置浏览器中搜索并直达 $directSearchName 教务登录入口',
    );
    results.add(directPortal);

    return results;
  }
